CREATE TABLE councils (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    round_id BIGINT NOT NULL REFERENCES registration_periods(id),
    location VARCHAR(200),
    report_date TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_councils_status CHECK (status IN ('DRAFT', 'ACTIVE', 'COMPLETED')),
    CONSTRAINT uq_councils_round_name UNIQUE (round_id, name)
);

CREATE TABLE council_members (
    council_id BIGINT NOT NULL REFERENCES councils(id) ON DELETE CASCADE,
    lecturer_id BIGINT NOT NULL REFERENCES users(id),
    role VARCHAR(20) NOT NULL,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (council_id, lecturer_id),
    CONSTRAINT ck_council_members_role CHECK (role IN ('PRESIDENT', 'SECRETARY', 'MEMBER'))
);

CREATE TABLE topic_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL UNIQUE REFERENCES topics(id),
    council_id BIGINT REFERENCES councils(id) ON DELETE SET NULL,
    reviewer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_councils_round ON councils(round_id);
CREATE INDEX idx_council_members_lecturer ON council_members(lecturer_id);
CREATE INDEX idx_topic_assignments_council ON topic_assignments(council_id);
CREATE INDEX idx_topic_assignments_reviewer ON topic_assignments(reviewer_id);
