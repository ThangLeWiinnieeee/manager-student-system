-- Original topic-level tables remain available for historical reconciliation.
CREATE TABLE group_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL UNIQUE REFERENCES group_topic_registrations(id),
    topic_id BIGINT NOT NULL REFERENCES topics(id),
    council_id BIGINT REFERENCES councils(id) ON DELETE SET NULL,
    reviewer_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    assigned_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- TV4: Cham diem, nhan xet va Tong hop ket qua
CREATE TABLE group_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL REFERENCES group_topic_registrations(id),
    topic_id BIGINT NOT NULL REFERENCES topics(id),
    evaluator_id BIGINT NOT NULL REFERENCES users(id),
    evaluation_type VARCHAR(20) NOT NULL,
    score_content NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    score_presentation NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    score_qa NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    total_score NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    comments VARCHAR(2000),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    submitted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_group_evaluations_type CHECK (evaluation_type IN ('REVIEWER', 'COUNCIL')),
    CONSTRAINT ck_group_evaluations_status CHECK (status IN ('DRAFT', 'SUBMITTED')),
    CONSTRAINT ck_group_evaluations_score CHECK (total_score >= 0.00 AND total_score <= 10.00),
    CONSTRAINT uq_group_evaluations_topic_evaluator UNIQUE (registration_id, evaluator_id)
);

CREATE TABLE group_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL REFERENCES group_topic_registrations(id),
    topic_id BIGINT NOT NULL REFERENCES topics(id),
    CONSTRAINT uq_group_result UNIQUE (registration_id),
    council_id BIGINT NOT NULL REFERENCES councils(id),
    reviewer_score NUMERIC(4, 2),
    council_avg_score NUMERIC(4, 2),
    final_score NUMERIC(4, 2),
    grade VARCHAR(30),
    conclusion VARCHAR(1000),
    president_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    president_confirmed_at TIMESTAMP WITH TIME ZONE,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_group_evaluations_topic ON group_evaluations(topic_id);
CREATE INDEX idx_group_evaluations_evaluator ON group_evaluations(evaluator_id);
CREATE INDEX idx_group_results_council ON group_results(council_id);
CREATE INDEX idx_group_results_published ON group_results(published);

