SELECT r.id,old.topic_id,old.council_id,old.reviewer_score,old.council_avg_score,old.final_score,old.grade,old.conclusion,old.president_confirmed,old.president_confirmed_at,old.published,old.published_at,old.created_at,old.updated_at
