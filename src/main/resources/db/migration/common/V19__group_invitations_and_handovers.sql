CREATE TABLE group_invitations (
    group_id BIGINT NOT NULL REFERENCES student_groups(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY (group_id, student_id)
);
CREATE INDEX ix_group_invitations_student ON group_invitations(student_id);

CREATE TABLE academic_handovers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES registration_periods(id),
    task VARCHAR(40) NOT NULL,
    target_id BIGINT NOT NULL,
    previous_user_id BIGINT NOT NULL REFERENCES users(id),
    replacement_user_id BIGINT NOT NULL REFERENCES users(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    reason VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_academic_handovers_course ON academic_handovers(course_id);
