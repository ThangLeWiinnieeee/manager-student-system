CREATE TABLE registration_windows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    round_type VARCHAR(20) NOT NULL,
    gv_start TIMESTAMP NOT NULL,
    gv_end TIMESTAMP NOT NULL,
    sv_start TIMESTAMP NOT NULL,
    sv_end TIMESTAMP NOT NULL,
    gvpb_deadline TIMESTAMP,
    council_report_date TIMESTAMP,
    legacy_course_id BIGINT UNIQUE,
    CONSTRAINT ck_registration_windows_type CHECK (round_type IN ('MON_HOC','NCKH','TLCN','KLTN'))
);

-- Each historical course keeps its own schedule; do not infer which old courses belong together.
INSERT INTO registration_windows (name,round_type,gv_start,gv_end,sv_start,sv_end,gvpb_deadline,council_report_date,legacy_course_id)
SELECT name,round_type,gv_start,gv_end,sv_start,sv_end,gvpb_deadline,council_report_date,id FROM registration_periods;

ALTER TABLE registration_periods ADD COLUMN period_id BIGINT REFERENCES registration_windows(id);
UPDATE registration_periods SET period_id = (SELECT w.id FROM registration_windows w WHERE w.legacy_course_id = registration_periods.id);
