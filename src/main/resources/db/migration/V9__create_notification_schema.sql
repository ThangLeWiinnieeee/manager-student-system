CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    content VARCHAR(4000) NOT NULL,
    target_role VARCHAR(20) NOT NULL DEFAULT 'ALL',
    pinned BOOLEAN NOT NULL DEFAULT FALSE,
    published BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notifications_target_role CHECK (target_role IN ('ALL', 'LECTURER', 'STUDENT'))
);

CREATE INDEX idx_notifications_published ON notifications(published, pinned DESC, created_at DESC);
CREATE INDEX idx_notifications_target_role ON notifications(target_role);
