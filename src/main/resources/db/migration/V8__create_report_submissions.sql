
CREATE TABLE report_submissions (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY
                                        PRIMARY KEY,

                                    group_id BIGINT NOT NULL
                                        REFERENCES student_groups(id),

                                    uploaded_by BIGINT NOT NULL
                                        REFERENCES users(id),

                                    original_filename VARCHAR(255) NOT NULL,

                                    stored_filename VARCHAR(80) NOT NULL UNIQUE,

                                    size_bytes BIGINT NOT NULL,

                                    content_type VARCHAR(100) NOT NULL
                                        DEFAULT 'application/pdf',

                                    uploaded_at TIMESTAMPTZ NOT NULL
                                        DEFAULT CURRENT_TIMESTAMP,

                                    CONSTRAINT ck_report_size
                                        CHECK (
                                            size_bytes > 0
                                                AND size_bytes <= 10485760
                                            )
);

CREATE INDEX idx_report_submissions_group
    ON report_submissions(group_id, uploaded_at DESC);
