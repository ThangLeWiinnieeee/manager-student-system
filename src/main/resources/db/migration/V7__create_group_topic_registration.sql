
CREATE TABLE group_topic_registrations (

                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY
                                               PRIMARY KEY,

                                           group_id BIGINT NOT NULL
                                               REFERENCES student_groups(id),

                                           topic_id BIGINT NOT NULL
                                               REFERENCES topics(id),

                                           status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

                                           rejection_reason VARCHAR(500),

                                           submitted_at TIMESTAMPTZ NOT NULL
                                                                       DEFAULT CURRENT_TIMESTAMP,

                                           reviewed_by BIGINT
                                               REFERENCES users(id),

                                           reviewed_at TIMESTAMPTZ,

                                           CONSTRAINT uq_group_topic_registration_group
                                               UNIQUE (group_id),

                                           CONSTRAINT ck_group_topic_registration_status
                                               CHECK (status IN (
                                                                 'PENDING',
                                                                 'APPROVED',
                                                                 'REJECTED'
                                                   ))
);

CREATE INDEX idx_group_topic_registration_topic
    ON group_topic_registrations(topic_id);

CREATE INDEX idx_group_topic_registration_status
    ON group_topic_registrations(status);
