CREATE TABLE evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL REFERENCES topics(id),
    evaluator_id BIGINT NOT NULL REFERENCES users(id),
    evaluation_type VARCHAR(20) NOT NULL,
    score_content NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    score_presentation NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    score_qa NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    total_score NUMERIC(4, 2) NOT NULL DEFAULT 0.00,
    comments VARCHAR(2000),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    submitted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_evaluations_type CHECK (evaluation_type IN ('REVIEWER', 'COUNCIL')),
    CONSTRAINT ck_evaluations_status CHECK (status IN ('DRAFT', 'SUBMITTED')),
    CONSTRAINT ck_evaluations_score CHECK (total_score >= 0.00 AND total_score <= 10.00),
    CONSTRAINT uq_evaluations_topic_evaluator UNIQUE (topic_id, evaluator_id)
);

CREATE TABLE topic_final_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL UNIQUE REFERENCES topics(id),
    council_id BIGINT NOT NULL REFERENCES councils(id),
    reviewer_score NUMERIC(4, 2),
    council_avg_score NUMERIC(4, 2),
    final_score NUMERIC(4, 2),
    grade VARCHAR(30),
    conclusion VARCHAR(1000),
    president_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    president_confirmed_at TIMESTAMP WITH TIME ZONE,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_evaluations_topic ON evaluations(topic_id);
CREATE INDEX idx_evaluations_evaluator ON evaluations(evaluator_id);
CREATE INDEX idx_topic_final_results_council ON topic_final_results(council_id);
CREATE INDEX idx_topic_final_results_published ON topic_final_results(published);
