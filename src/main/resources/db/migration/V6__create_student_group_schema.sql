CREATE TABLE student_groups (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                name VARCHAR(150) NOT NULL,

                                round_id BIGINT NOT NULL
                                    REFERENCES registration_periods(id),

                                leader_id BIGINT
                                    REFERENCES users(id),

                                created_at TIMESTAMP WITH TIME ZONE
                                                  NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT uq_student_groups_round_name
                                    UNIQUE (round_id, name)
);

CREATE TABLE student_group_members (
                                       group_id BIGINT NOT NULL
                                           REFERENCES student_groups(id) ON DELETE CASCADE,

                                       student_id BIGINT NOT NULL
                                           REFERENCES users(id),

                                       joined_at TIMESTAMP WITH TIME ZONE
                                           NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                       PRIMARY KEY (group_id, student_id)
);

CREATE INDEX idx_student_groups_round
    ON student_groups(round_id);

CREATE INDEX idx_student_groups_leader
    ON student_groups(leader_id);

CREATE INDEX idx_student_group_members_student
    ON student_group_members(student_id);
